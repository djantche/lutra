#!/usr/bin/env python3
"""Generates `src/rpc_dispatch.rs`: the table that turns a command name and a JSON object of
arguments into a call to the matching function of `src/lib.rs`.

Every function marked with a `// @rpc` line above it becomes a command. Run it after adding,
removing or changing a command:

    python3 backend/tools/gen_rpc.py
"""
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
source = (ROOT / "src" / "lib.rs").read_text()

pattern = re.compile(
    r"// @rpc\s*((?:pub )?async fn|(?:pub )?fn)\s+(\w+)\s*\((.*?)\)\s*(->\s*[^{]+)?\{", re.S
)


def camel(name: str) -> str:
    head, *tail = name.split("_")
    return head + "".join(word.capitalize() for word in tail)


def split_args(text: str):
    """Splits a parameter list on top-level commas (generics contain commas too)."""
    parts, depth, current = [], 0, ""
    for char in text:
        if char in "<([":
            depth += 1
        elif char in ">)]":
            depth -= 1
        if char == "," and depth == 0:
            parts.append(current)
            current = ""
        else:
            current += char
    if current.strip():
        parts.append(current)
    return [part.strip() for part in parts]


arms = []
for match in pattern.finditer(source):
    kind, name, raw_args, raw_ret = match.groups()
    is_async = "async" in kind
    ret = (raw_ret or "").replace("->", "").strip()
    lines, call_args = [], []
    for part in split_args(raw_args):
        arg_name, arg_type = [piece.strip() for piece in part.split(":", 1)]
        if arg_type == "AppHandle":
            call_args.append("app.clone()")
        elif arg_type.startswith("State<"):
            inner = re.search(r"State<'_,\s*([\w:]+)>", arg_type).group(1)
            call_args.append(f"app.state::<{inner}>()")
        else:
            lines.append(f'let {arg_name}: {arg_type} = rpc::arg(args, "{camel(arg_name)}")?;')
            call_args.append(arg_name)
    call = f"{name}({', '.join(call_args)})"
    if is_async:
        call = f"host::async_runtime::block_on({call})"
    if ret.startswith("Result<Vec<u8>"):
        tail = f"{call}.map(|bytes| rpc::bytes(&bytes))"
    elif ret.startswith("Result<"):
        tail = f"{call}.and_then(rpc::to_value)"
    else:
        tail = f"rpc::to_value({call})"
    body = "\n            ".join(lines + [tail])
    arms.append(f'        "{name}" => {{\n            {body}\n        }}')

out = (
    "// Generated by backend/tools/gen_rpc.py from the `// @rpc` functions of lib.rs: do not edit.\n"
    "// Included at the end of lib.rs, so every type and function is in scope.\n\n"
    "/// Runs one command of the shell. `args` is the JSON object the interface sent.\n"
    "pub(crate) fn dispatch(\n"
    "    app: &AppHandle,\n"
    "    command: &str,\n"
    "    args: &serde_json::Value,\n"
    ") -> Result<serde_json::Value, String> {\n"
    "    match command {\n" + ",\n".join(arms) + ",\n"
    '        other => Err(format!("unknown command `{other}`")),\n'
    "    }\n}\n"
)
target = ROOT / "src" / "rpc_dispatch.rs"
target.write_text(out)
subprocess.run(["rustfmt", "--edition", "2024", str(target)], check=True)
print(f"{len(arms)} commands")
